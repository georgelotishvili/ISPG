print("\nშესვლელი (PDG 2024):")
print(f"   UP:     m_u = {m_u:.2f}    m_c = {m_c:.1f}      m_t = {m_t:.0f}")
print(f"   DOWN:   m_d = {m_d:.2f}    m_s = {m_s:.1f}      m_b = {m_b:.0f}")
print(f"   ლეპტ.:  m_e = {m_e:.4f}  m_μ = {m_mu:.3f}  m_τ = {m_tau:.2f}")

# ===================================================================
# A. Koide Q თითოეულ სექტორზე
# ===================================================================

def koide_Q(masses):
    """Q = Σm / (Σ√m)²"""
    return sum(masses) / sum(np.sqrt(m) for m in masses)**2

print("\n" + "-" * 72)
print(" A. Koide-ს Q სექტორების მიხედვით")
print("-" * 72)

Q_lep = koide_Q([m_e, m_mu, m_tau])
Q_up = koide_Q([m_u, m_c, m_t])
Q_down = koide_Q([m_d, m_s, m_b])

print(f"\n   ლეპტონები (e, μ, τ):    Q = {Q_lep:.6f}  ( 2/3 = 0.6667)")
print(f"   UP კვარკები (u, c, t):   Q = {Q_up:.6f}")
print(f"   DOWN კვარკები (d, s, b): Q = {Q_down:.6f}")

print(f"\n   ცდომილება 2/3-დან:")
print(f"     ლეპტონები:   {abs(Q_lep - 2/3)*100/Q_lep:.4f}%")
print(f"     UP:          {abs(Q_up - 2/3)*100/Q_up:.2f}%")
print(f"     DOWN:        {abs(Q_down - 2/3)*100/Q_down:.2f}%")

