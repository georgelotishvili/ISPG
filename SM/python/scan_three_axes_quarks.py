# მნიშვნელოვანი: კვარკის მასა სქემა-დამოკიდებულია
# (თავისუფალი კვარკი არ არსებობს, ე.ი. პირდაპირი გაზომვა არ ხდება).
# ვიყენებთ PDG centralral values.

m_u = 2.16         # MeV  (MS-bar, 2 GeV)
m_d = 4.67         # MeV  (MS-bar, 2 GeV)
m_s = 93.4         # MeV  (MS-bar, 2 GeV)
m_c = 1270         # MeV  (MS-bar, at m_c)
m_b = 4180         # MeV  (MS-bar, at m_b)
m_t = 172690       # MeV  (pole mass)

# ლეპტონები (შედარებისთვის)
m_e = 0.51099895
m_mu = 105.6583755
