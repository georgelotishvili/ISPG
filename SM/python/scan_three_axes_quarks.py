def find_near_integer(x, tol=0.05):
    """უახლოესი მთელი რიცხვი და ცდომილება"""
    n = round(x)
    err = abs(x - n) / x
    return n, err

# "N-სივრცე" სხვადასხვა მიახლოებით
# თუ m ∝ N², მაშინ N ∝ √m (ანუ Mathieu-ულია)

print(f"\n   UP კვარკები (m ∝ N² ანზაცი):")
ratio_c_u = np.sqrt(m_c/m_u)
ratio_t_u = np.sqrt(m_t/m_u)
n1, e1 = find_near_integer(ratio_c_u)
n2, e2 = find_near_integer(ratio_t_u)
print(f"     √(m_c/m_u) = {ratio_c_u:.4f}   ≈ {n1}  (ცდომ. {e1*100:.2f}%)")
print(f"     √(m_t/m_u) = {ratio_t_u:.4f}   ≈ {n2}  (ცდომ. {e2*100:.2f}%)")

print(f"\n   DOWN კვარკები (m ∝ N² ანზაცი):")
ratio_s_d = np.sqrt(m_s/m_d)
ratio_b_d = np.sqrt(m_b/m_d)
n3, e3 = find_near_integer(ratio_s_d)
n4, e4 = find_near_integer(ratio_b_d)
print(f"     √(m_s/m_d) = {ratio_s_d:.4f}    ≈ {n3}  (ცდომ. {e3*100:.2f}%)")
print(f"     √(m_b/m_d) = {ratio_b_d:.4f}    ≈ {n4}  (ცდომ. {e4*100:.2f}%)")

print(f"\n   ლეპტონები (შედარებისთვის):")
print(f"     √(m_μ/m_e) = {np.sqrt(m_mu/m_e):.4f}  (არ არის მთელი)")
print(f"     √(m_τ/m_e) = {np.sqrt(m_tau/m_e):.4f}  ≈ 59 ✓")

