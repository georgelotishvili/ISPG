"""
ISPG — Phase 5: Koide + "59" → 207 ავტომატური?
================================================================

ანზაცი:
   Koide-ს იდენტობა 3 მასაზე = ერთი კონსტრეინტი.
   ე.ი. 3 მასის 3 თანაფარდობიდან, Koide-ის შემდეგ, ცალკე პარამეტრი
   რჩება მხოლოდ 1 (არა 2!).

   ცხადად: თუ ვიცით m_τ/m_e, მაშინ Koide-ით m_μ/m_e პროგნოზირებულია.

ვცდით:
   თუ N_τ/N_e = 59 (ცნობილი მთელი რიცხვი გუშინდელი სკანიდან),
   მაშინ Koide უნდა პროგნოზირებდეს N_μ/N_e = 14.4-ს
   და ე.ი. N_μ = 72-ს ავტომატურად.

   თუ ეს მუშაობს, პარამეტრების ბიუჯეტი:
      4 → 3
   და 72-ის "ემპირიული ფიტი" ფაქტიურად გამოდის Koide-დან!
"""

import numpy as np

print("=" * 72)
print(" Phase 5 — Koide + 59 → 72 ავტომატური შემოწმება")
print("=" * 72)

# ===================================================================
# A. Koide-ს განტოლების გადახსნა
# ===================================================================

print("""
   Koide: (√m_e + √m_μ + √m_τ)² / (m_e + m_μ + m_τ) = 3/2

   ავღნიშნოთ x = √(m_μ/m_e),  y = √(m_τ/m_e)
   (ანუ N-სივრცეში: x = N_μ/N_e,  y = N_τ/N_e)

   Koide-ის გადაკეთება:
      (1 + x + y)² = (3/2)(1 + x² + y²)

   ე.ი. x² - (4y+4)x + (y² - 4y + 1) = 0

   კვადრატის ამოხსნა x-თვის (y-ის ფუნქცია):
      x = (2y+2) ± √3 · √(y² + 4y + 1)
""")

# ===================================================================
# B. დაკვირვებულ მნიშვნელობებზე შემოწმება
# ===================================================================

m_e = 0.51099895
m_mu = 105.6583755
m_tau = 1776.86

x_obs = np.sqrt(m_mu/m_e)
y_obs = np.sqrt(m_tau/m_e)

print("   B. დაკვირვებული:")
print(f"      x_obs = √(m_μ/m_e) = {x_obs:.4f}")
print(f"      y_obs = √(m_τ/m_e) = {y_obs:.4f}")
print(f"      → y ≈ 59 (მთელი!), x ≈ 14.4 (არა მთელი)")

# ===================================================================
# C. ვანდობთ y = 59 ზუსტად → პროგნოზი x-სთვის
# ===================================================================

print("\n" + "-" * 72)
print(" C. თუ y = 59 ზუსტად (სტრუქტურული ფაქტი)...")
print("-" * 72)

y_structural = 59.0
# ვიღებთ "−" ბრანჩს (უფრო მცირე ფესვი)
x_predicted = (2*y_structural + 2) - np.sqrt(3) * np.sqrt(y_structural**2 + 4*y_structural + 1)

print(f"\n   x = 2y+2 - √3·√(y²+4y+1)")
print(f"     = {2*y_structural+2} - √3·√{y_structural**2+4*y_structural+1}")
print(f"     = {2*y_structural+2} - {np.sqrt(3)*np.sqrt(y_structural**2+4*y_structural+1):.4f}")
print(f"     = {x_predicted:.4f}")

print(f"\n   დაკვირვება: x_obs = {x_obs:.4f}")
print(f"   პროგნოზი:   x = {x_predicted:.4f}")
err = abs(x_predicted - x_obs) / x_obs * 100
print(f"   ცდომილება:  {err:.3f}%")

# ===================================================================
# D. N-სივრცეში
# ===================================================================

print("\n" + "-" * 72)
print(" D. N-სივრცეში (MASS ნაშრომის Mathieu ინდექსი)")
print("-" * 72)

N_e = 5
N_tau_structural = 59 * N_e  # = 295

# Koide-ით ვიანგარიშებთ N_μ-ს
N_mu_predicted = x_predicted * N_e

print(f"\n   N_e = {N_e} (Mathieu პირველი სტაბილური ზონა — დამტკიცებული)")
print(f"   N_τ = {N_tau_structural} (= 59·N_e, სტრუქტურული ვარაუდი)")
print(f"   N_μ (Koide-ით პროგნოზი) = {N_mu_predicted:.3f}")
print(f"   N_μ (დაკვირვება MASS-დან) = 72")
err_N = abs(N_mu_predicted - 72) / 72 * 100
print(f"   ცდომილება:            {err_N:.2f}%")

# ===================================================================
# E. რას ნიშნავს
# ===================================================================

print("\n" + "=" * 72)
print(" E. შედეგი")
print("=" * 72)

print(f"""
   დადასტურება:
   ═══════════
   მოცემული N_τ/N_e = 59 (ერთი მთელი რიცხვი),
   Koide-ს იდენტობა ავტომატურად პროგნოზირებს:
      N_μ/N_e = {x_predicted:.4f}  →  N_μ ≈ {N_mu_predicted:.1f}
   დაკვირვებული: N_μ = 72  →  ცდომილება {err_N:.2f}%

   ე.ი. "72" არ არის ცალკე ემპირიული ფიტი!
   ────────────────────────────────────────────
   "72" გამოდის Koide-დან + N_τ/N_e = 59-დან.
   ცალკე "კოდის გახსნა" 72-ისთვის არ გვჭირდება.

   პარამეტრების ბიუჯეტი ხელახლა:
   ────────────────────────────────────────────
   Phase 4-ში: 4 პარამეტრი (m_e, k_y/k_x, k_z/k_x, G_F)
   ახლა:       3 პარამეტრი (m_e, N_τ/N_e = 59, G_F)
               + Koide იდენტობა ფუნდამენტურად

   რაც ღიაა:
   ───────────
   რატომ ზუსტად 59? ეს ერთადერთი შეუზღუდავი რიცხვია დარჩენილი.
   (შესაძლოა კავშირი ISPG-ის D₃ სიმეტრიასთან ან Mathieu ქცევასთან.)
""")

# ===================================================================
# F. მეორე ბრანჩი: შეიძლება ექვივალენტური ამოხსნა?
# ===================================================================

print("-" * 72)
print(" F. კვადრატის მეორე ფესვი (ალტერნატივა)")
print("-" * 72)

x_alt = (2*y_structural + 2) + np.sqrt(3) * np.sqrt(y_structural**2 + 4*y_structural + 1)
print(f"\n   x+ = 2y+2 + √3·√(y²+4y+1) = {x_alt:.4f}")
print(f"   → N_μ_alt = {x_alt*N_e:.1f}")
print(f"   დაკვირვება: 72. არა, ეს ბრანჩი არ შეესაბამება.")
print(f"   ფიზიკური ბრანჩი = მცირე ფესვი, რომელიც ემთხვევა დაკვირვებას.")

# ===================================================================
# G. სტაბილურობა — რა ხდება სხვა y-ისთვის?
# ===================================================================

print("\n" + "-" * 72)
print(" G. სენსიტიურობის ტესტი (რა თუ y-ი სხვა იქნებოდა?)")
print("-" * 72)

print(f"\n   y (N_τ/N_e)   N_μ_predicted   m_μ/m_e_pred")
print(f"   ───────────────────────────────────────────")
for y_test in [50, 55, 58, 59, 60, 62, 65, 70]:
    x_t = (2*y_test+2) - np.sqrt(3) * np.sqrt(y_test**2 + 4*y_test + 1)
    N_mu_t = x_t * N_e
    m_ratio_t = x_t**2
    marker = "  ← დაკვირვება" if y_test == 59 else ""
    print(f"     {y_test}           {N_mu_t:6.2f}         {m_ratio_t:6.2f}{marker}")

print(f"\n   დაკვირვებული m_μ/m_e = {m_mu/m_e:.2f}")

print("\n" + "=" * 72)
print(" Phase 5 — დასრულდა")
print("=" * 72)
