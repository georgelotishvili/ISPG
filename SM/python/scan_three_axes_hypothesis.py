"""
ISPG — 3-ორთოგონალური ღერძის ჰიპოთეზა ლეპტონის თაობებისთვის
================================================================

ჰიპოთეზა (მომხმარებლის):
  სივრცე 3D. სკალარული ველი ვიბრირებს 3 ორთოგონალური ღერძით.
  თითო ღერძი = თითო თაობა:
    x-ღერძი: ელექტრონი (მარადიული)
    y-ღერძი: მიუონი    (დამპფირება ~10⁻⁶ წმ)
    z-ღერძი: ტაუ       (დამპფირება ~10⁻¹³ წმ)

  ANSATZ-ი:
    m_i c² = ℏ ω_i           (მასა = სიხშირე)
    ω_i = √(k_i / m₀)         (3 ზამბარა)
    სიცოცხლე ∝ 1/γ_i (ლაბში)
    სიცოცხლე ∝ ω_i/γ_i (შიდა ციკლებში — "პროცესის დრო")

რას ვამოწმებთ (3 ფაზა):
  A. სიხისტეები k_x : k_y : k_z — რა ბუნებრივი თანაფარდობა გამოდის?
  B. დამპფირება — ლაბ წამებში vs შიდა ციკლებში
  C. Koide-ს გეომეტრია — 45° კუთხის ვერიფიკაცია

მიზანი: არა "ფიტი ყველა ფასად" — არამედ ვნახოთ მოდელი ბუნებრივად
        გამოიღებს თუ არა დაკვირვებულ რიცხვებს.
"""

import numpy as np

# ===================================================================
# 1. სამყარო: PDG მასები და სიცოცხლის ხანგრძლივობები
# ===================================================================

# მასები MeV-ში (PDG 2024)
m_e = 0.51099895      # ელექტრონი
m_mu = 105.6583755    # მიუონი
m_tau = 1776.86       # ტაუ

# სიცოცხლის ხანგრძლივობა წამებში (PDG 2024)
tau_e = float('inf')           # ელექტრონი — მარადიული
tau_mu = 2.1969811e-6          # მიუონი
tau_tau = 290.3e-15            # ტაუ ≈ 2.903×10⁻¹³ წმ

# ფუნდამენტური მუდმივები
hbar_MeV_s = 6.582119569e-22   # ℏ MeV·წმ-ში
c = 2.99792458e8               # სინათლის სიჩქარე

print("=" * 72)
print(" ISPG — 3-ორთოგონალური ღერძის ჰიპოთეზის შემოწმება")
print("=" * 72)
print(f"\nლეპტონების მასები (MeV/c²):")
print(f"   m_e   = {m_e:.6f}")
print(f"   m_μ   = {m_mu:.6f}    (ფარდობა m_μ/m_e = {m_mu/m_e:.4f})")
print(f"   m_τ   = {m_tau:.6f}   (ფარდობა m_τ/m_e = {m_tau/m_e:.4f})")
print(f"\nსიცოცხლე (წამები):")
print(f"   τ_e   = ∞             (მარადიული)")
print(f"   τ_μ   = {tau_mu:.4e}    ({tau_mu*1e6:.3f} მკწმ)")
print(f"   τ_τ   = {tau_tau:.4e}    ({tau_tau*1e15:.3f} ფწმ)")

# ===================================================================
# ფაზა A — სიხისტეების თანაფარდობა (მასების გამო)
# ===================================================================

print("\n" + "=" * 72)
print(" ფაზა A — რა სიხისტეების თანაფარდობა მოეთხოვება ჰიპოთეზას?")
print("=" * 72)

# თუ 3 ღერძი = 3 დამოუკიდებელი ჰარმონიული ოსცილატორი ერთი-იგივე ინერციით m₀,
# მაშინ ω_i = √(k_i / m₀), ე.ი. k_i ∝ ω_i² ∝ m_i² (თუ m ∝ ω).
# ფარდობითი სიხისტეები:

k_ratios_direct = {
    'k_y/k_x': (m_mu/m_e)**2,      # (207)² ≈ 42,800
    'k_z/k_x': (m_tau/m_e)**2,     # (3477)² ≈ 12,100,000
    'k_z/k_y': (m_tau/m_mu)**2,    # (16.82)² ≈ 283
}

print("\nA.1 — ჰიპოთეზა: m ∝ ω → k_i ∝ m_i² (ერთი ინერცია)")
for name, val in k_ratios_direct.items():
    print(f"   {name} = {val:,.2f}")

# ალტერნატივა: ფიქსირებული სიხისტე, ცვალებადი ინერცია
# ან: m ∝ ω² (Mathieu-ული ანზაცი, როგორც MASS ნაშრომში)
# მაშინ ω_i ∝ √m_i, და k_i ∝ ω_i² ∝ m_i

k_ratios_sqrt = {
    'k_y/k_x': m_mu/m_e,           # 207
    'k_z/k_x': m_tau/m_e,          # 3477
    'k_z/k_y': m_tau/m_mu,         # 16.82
}

print("\nA.2 — ალტერნატივა: m ∝ ω² → k_i ∝ m_i")
for name, val in k_ratios_sqrt.items():
    print(f"   {name} = {val:,.2f}")

# ბუნებრივობის ტესტი: რამდენად ახლოსაა რაციოები მარტივ
# მთელ რიცხვებს, ფიბონაჩი რიცხვებს, ან პრიმებს?

def closest_integer_ratio(x, max_int=500):
    """უახლოესი a/b სადაც a, b ≤ max_int"""
    best = (1, 1, float('inf'))
    for a in range(1, max_int+1):
        for b in range(1, max_int+1):
            err = abs(x - a/b) / x
            if err < best[2]:
                best = (a, b, err)
    return best

print("\nA.3 — ბუნებრივობის ტესტი: რამდენად მთელ-რიცხვიანია რაციოები?")
for label, ratios in [("m∝ω", k_ratios_direct), ("m∝ω²", k_ratios_sqrt)]:
    print(f"\n   {label}:")
    for name, val in ratios.items():
        a, b, err = closest_integer_ratio(val, max_int=500)
        print(f"     {name} = {val:,.2f} ≈ {a}/{b} (ცდომ. {err*100:.2f}%)")

# ===================================================================
# ფაზა B — დამპფირება ლაბ წამებში vs ციკლებში
# ===================================================================

print("\n" + "=" * 72)
print(" ფაზა B — დამპფირების კოეფიციენტები")
print("=" * 72)

# ω (რად/წმ) = m c² / ℏ
omega_e = m_e / hbar_MeV_s
omega_mu = m_mu / hbar_MeV_s
omega_tau = m_tau / hbar_MeV_s

print(f"\nB.1 — შიდა სიხშირეები (რად/წმ):")
print(f"   ω_e   = {omega_e:.4e}")
print(f"   ω_μ   = {omega_mu:.4e}")
print(f"   ω_τ   = {omega_tau:.4e}")

# დამპფირების ∝ 1/τ_life (ლაბ ჩარჩოში)
gamma_e_lab = 0.0
gamma_mu_lab = 1 / tau_mu
gamma_tau_lab = 1 / tau_tau

print(f"\nB.2 — დამპფირება ლაბ ჩარჩოში γ = 1/τ (ჰც):")
print(f"   γ_e^lab = 0   (მარადიული)")
print(f"   γ_μ^lab = {gamma_mu_lab:.4e} ჰც")
print(f"   γ_τ^lab = {gamma_tau_lab:.4e} ჰც")
print(f"   γ_τ^lab / γ_μ^lab = {gamma_tau_lab/gamma_mu_lab:,.0f}")

# შიდა ციკლების რაოდენობა სიცოცხლის განმავლობაში
cycles_mu = omega_mu * tau_mu / (2 * np.pi)
cycles_tau = omega_tau * tau_tau / (2 * np.pi)

print(f"\nB.3 — შიდა ციკლების რაოდენობა სიცოცხლის განმავლობაში:")
print(f"   N_cycles(e)  = ∞   (მარადიული)")
print(f"   N_cycles(μ)  = {cycles_mu:.4e}")
print(f"   N_cycles(τ)  = {cycles_tau:.4e}")
print(f"   შემცირების ფაქტორი: μ → τ : {cycles_mu/cycles_tau:,.1f}×")

# დამპფირება ციკლის ერთეულში (γ_per_cycle = γ/ω)
gamma_per_cycle_mu = gamma_mu_lab / omega_mu
gamma_per_cycle_tau = gamma_tau_lab / omega_tau

print(f"\nB.4 — დამპფირება ციკლის ერთეულში (γ/ω):")
print(f"   γ/ω (e)  = 0")
print(f"   γ/ω (μ)  = {gamma_per_cycle_mu:.4e}")
print(f"   γ/ω (τ)  = {gamma_per_cycle_tau:.4e}")
print(f"   ფარდობა τ/μ (γ/ω): {gamma_per_cycle_tau/gamma_per_cycle_mu:.4e}")

# ===================================================================
# ფაზა C — Koide-ს გეომეტრიული იდენტობა
# ===================================================================

print("\n" + "=" * 72)
print(" ფაზა C — Koide-ს 45° კუთხე (3-ორთოგონალური ვექტორი)")
print("=" * 72)

# ვექტორი v = (√m_e, √m_μ, √m_τ) სამგანზომილებიანი სივრცეში
v = np.array([np.sqrt(m_e), np.sqrt(m_mu), np.sqrt(m_tau)])
v_norm = np.linalg.norm(v)
diag = np.array([1, 1, 1]) / np.sqrt(3)  # დიაგონალის ერთეული ვექტორი

cos_theta = np.dot(v, diag) / v_norm
theta_rad = np.arccos(cos_theta)
theta_deg = np.degrees(theta_rad)

Q_koide = (m_e + m_mu + m_tau) / (np.sqrt(m_e) + np.sqrt(m_mu) + np.sqrt(m_tau))**2

print(f"\nC.1 — ვექტორი v = (√m_e, √m_μ, √m_τ):")
print(f"   |v|        = {v_norm:.4f}")
print(f"   v · n̂     = {np.dot(v, diag):.4f}")
print(f"   cos θ      = {cos_theta:.6f}")
print(f"   cos²θ      = {cos_theta**2:.6f}")
print(f"   θ          = {theta_deg:.4f}°")

print(f"\nC.2 — Koide-ს Q:")
print(f"   Q (პირდაპირ)        = {Q_koide:.6f}")
print(f"   Q = 1/(3cos²θ)      = {1/(3*cos_theta**2):.6f}")
print(f"   2/3                 = {2/3:.6f}")
print(f"   ცდომილება 2/3-დან   = {abs(Q_koide - 2/3) * 100:.4f}%")

print(f"\nC.3 — ლიმიტები (ყოველთვის დადებითი კომპონენტებით):")
print(f"   სრული სიმეტრია (ღერძები ერთნაირი):  Q = 1/3 = 0.3333  (θ = 0°)")
print(f"   რეალური ლეპტონები:                   Q = 2/3 = 0.6667  (θ = 45°)")
print(f"   ერთი ღერძი დომინირებს:               Q = 1.0000         (θ ≈ 54.74°)")

print(f"\nC.4 — ენერგეტიკული ექვიპარტიცია:")
E_coherent = cos_theta**2  # "კოლექტიური" (დიაგონალური) წილი
E_deviation = 1 - cos_theta**2  # "გადახრის" წილი
print(f"   კოლექტიური ენერგია (დიაგონალი):  {E_coherent*100:.2f}%")
print(f"   გადახრის ენერგია (ტრეისლესი):     {E_deviation*100:.2f}%")
print(f"   → 50/50 ბალანსი ✓")

# ===================================================================
# ფაზა D — დასკვნა
# ===================================================================

print("\n" + "=" * 72)
print(" ფაზა D — დასკვნა")
print("=" * 72)

