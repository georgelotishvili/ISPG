# Q = ელ. მუხტი, T3_L = სუსტი იზოსპინი (მარცხენა), Y_L = hypercharge (მარცხენა)
# N_c = ფერი (1 ლეპტონს, 3 ქვარკს)
# N_obs = დაკვირვებული Mathieu-ინდექსი

particles = [
    # name,   Q,      T3_L,   Y_L,    N_c, N_obs (m_eff/m_e ფესვის მხრივ)
    ("e",   -1.0,    -0.5,   -1.0,    1,   5),
    ("nu_e", 0.0,    +0.5,   -1.0,    1,   None),  # ნეიტრინო: მასა ~ 0
    ("u",   +2/3,    +0.5,   +1/3,    3,   10),
    ("d",   -1/3,    -0.5,   +1/3,    3,   15),
]


def gen1_formula(Q, Nc):
    """Gen-1 ფორმულა N = 5·[1 + N_c·(1−|Q|)]."""
    return 5 * (1 + Nc * (1 - abs(Q)))


