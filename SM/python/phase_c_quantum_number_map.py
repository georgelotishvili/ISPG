print("-" * 70)

for name, Q, T3, Y, Nc, N_obs in particles:
    N_pred = gen1_formula(Q, Nc)
    if N_obs is None:
        status = f"⚠ ნეიტრინო: ფორმულა → {N_pred}, მასა ≈ 0 → არასრული"
    elif N_pred == N_obs:
        status = "✓ ზუსტი"
    else:
        err = 100 * abs(N_pred - N_obs) / N_obs
        status = f"✗ ცდომ. {err:.1f}%"
    N_obs_s = f"{N_obs}" if N_obs is not None else "—"
    print(f"{name:<6}{Q:>7.3f}{T3:>7.2f}{Y:>7.3f}{Nc:>5}{N_pred:>8}{N_obs_s:>8}  {status}")

