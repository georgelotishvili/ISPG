"""
ISPG — სიცოცხლის ხანგრძლივობა × N-ის ხარისხი
================================================
კითხვა:  არის თუ არა უცვლელი კომბინაცია τ_life × f(N)?

სტანდარტული სუსტი დაშლა:  Γ ∝ G_F² · m⁵
MASS paper-ში:              m ∝ N²
  →  Γ ∝ N¹⁰,  τ_life ∝ 1/N¹⁰
"""

import numpy as np

# CODATA / PDG
m_e   = 0.51099895       # MeV
m_mu  = 105.6583755      # MeV
m_tau = 1776.86          # MeV

tau_mu_s  = 2.1969811e-6   # წმ
tau_tau_s = 2.903e-13      # წმ
# ელექტრონი: > 6.6e28 წელი = 2.08e36 წმ (არსებითად მარადიული)

# Mathieu ladder N
N_e, N_mu, N_tau = 5, 72, 295

print("=" * 70)
print("  სიცოცხლის ხანგრძლივობა × N-ის ხარისხი")
print("=" * 70)

# რა შემცველ კონსტანტას ვამოწმებთ:
#   C_k = τ_life · N^k
#   თუ k-სთვის C იგივეა μ და τ-სთვის — შესაბამისობა ნაპოვნია.
print(f"\n  ვეძებ იმ k-ს, რომელსაც τ × N^k = const:")
print(f"  {'k':>4} {'τ_μ · N_μ^k':>18} {'τ_τ · N_τ^k':>18} {'ფარდობა':>10}")
print("  " + "-" * 60)

for k in [0, 2, 4, 5, 6, 8, 10, 11, 12]:
    A = tau_mu_s  * N_mu**k
    B = tau_tau_s * N_tau**k
    ratio = A / B
    print(f"  {k:>4} {A:>18.3e} {B:>18.3e} {ratio:>10.3f}")

# ზუსტი k რომელიც აძლევს ფარდობას = 1
# τ_μ · 72^k = τ_τ · 295^k
# ln(τ_μ/τ_τ) = k · ln(295/72)
k_exact = np.log(tau_mu_s / tau_tau_s) / np.log(N_tau / N_mu)
print(f"\n  ზუსტი k (ფარდობა = 1):  k* = {k_exact:.4f}")

# სტანდარტული ფიზიკა: τ ∝ 1/m⁵ = 1/N¹⁰ გამრავლებული „არხთა რიცხვზე"
# ტაუს აქვს ≈5 დაშლის არხი:  τ→eνν, τ→μνν, + 3 კვარკის ფერის არხი (ჰადრონული)
# ამიტომ:  τ_μ · N_μ^10  /  (τ_τ · N_τ^10)  ≈ N_channels_tau ≈ 5
k = 10
A = tau_mu_s  * N_mu**k
B = tau_tau_s * N_tau**k
channels = A / B
print(f"\n  k=10 შემთხვევაში: ფარდობა = {channels:.3f}")
print(f"  ფიზიკური ინტერპრეტაცია: ტაუს ~{channels:.2f} დაშლის არხი აქვს")
print(f"  (თეორიული: 2 ლეპტონური + 3 ფერი ჰადრონული = 5)")

# ელექტრონის შემთხვევა
print(f"\n  ელექტრონი:")
print(f"    თუ იგივე კონსტანტა იქნებოდა:")
C_ref = tau_mu_s * N_mu**10
tau_e_predicted = C_ref / (N_e**10)
tau_e_sec = tau_e_predicted
# გადავიყვანოთ წელებში
tau_e_years = tau_e_sec / (365.25 * 24 * 3600)
print(f"    τ_e (პროგნ., k=10) = {tau_e_sec:.3e} წმ = {tau_e_years:.3e} წელი")
print(f"    დაკვირვებული:       > 6.6e28 წელი (რეალურად მარადიული)")
print(f"    ანუ ელექტრონი **არღვევს** პროგნოზს — სრულიად განსხვავებულ რეჟიმშია.")
print(f"    მიზეზი: მის ქვემოთ არ არის მსუბუქი ცხ. ლეპტონი, სადაც გადავიდეს.")

print("\n" + "=" * 70)
print("  მთავარი დასკვნა")
print("=" * 70)
print(f"""
  μ ↔ τ კავშირი:
     τ × N^10 ≈ const × (ღია არხთა რიცხვი)
     ფარდობა ≈ 5.7  ←  ტაუს ~5 არხი
     ((N_c=3 ფერი) + 2 ლეპტონი = 5, SM tree-level)

  ε ↔ (μ,τ) კავშირი:
     ელექტრონი ჩვეულებრივად არ ჯდება ფორმულაში —
     ის **მარადიულია** არა ფორმულის გამო, არამედ იმიტომ, რომ
     მისი დაშლის საბოლოო მდგომარეობა არ არსებობს (კიბის ბოლო).

  IQ-ტესტის ენაზე:
     5, 72, 295 — კანონზომიერება არის სტანდარტული სუსტი დაშლის
     კანონის პირდაპირი შედეგი (Γ ∝ m⁵ ∝ N¹⁰).
     სიცოცხლის ხანგრძლივობა **არ** იძლევა დამატებით ინფორმაციას
     იმის გარდა, რაც უკვე იცოდა MASS paper-მა — ის უბრალოდ
     ამოწმებს, რომ m ∝ N² ფორმულა სტრუქტურულია.
""")
