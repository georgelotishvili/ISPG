"""
ISPG — Phase 7: ვეძებთ 59-ს პულსონის Mathieu სტრუქტურაში
================================================================

ცნობილი:
   - პულსონის ფონი → Mathieu განტოლება ψ'' + [a − 2q·cos(2τ)]ψ = 0
   - q = 1.853 (პულსონის პროფილიდან)
   - პირველი სტაბილური ზონა: N = 5 (ელექტრონი)
   - m_N ∝ b_N(q)-ს, სადაც b_N ≈ N² დიდი N-სთვის

საძიებო საკითხი:
   რატომ N_τ/N_e = 59 ზუსტად?
   Mathieu განტოლებაში q=1.853-ზე რაიმე სპეციალური ქცევაა N≈59-სა და
   N≈295-ის გარშემო?

რას ვამოწმებთ:
   A. Mathieu b_N(q) კოეფიციენტი N=1..400 დიაპაზონზე
   B. გადახრა b_N ≈ N² ასიმპტოტიდან (რა ჩანს ცალკეული N-ისთვის?)
   C. ფარდობა b_N/N² — რიპლები ან ნიშნები?
   D. სპეციალური N-ები: N_e=5, N_μ=72, N_τ=295
"""

import numpy as np
from scipy.special import mathieu_a, mathieu_b

q = 1.853

print("=" * 72)
print(f" Phase 7 — 59 ძებნა Mathieu-ს სტრუქტურაში (q = {q})")
print("=" * 72)

# ===================================================================
# A. Mathieu ეიგენვალუების გამოთვლა
# ===================================================================

print("\n" + "-" * 72)
print(" A. Mathieu ეიგენვალუები a_N(q) ფართო რანჯზე")
print("-" * 72)

# მცირე N: მიუონი 72 ცოტათი "მაღალია" — ვეძებთ რამდენიმე შუა წერტილს
N_interesting = [5, 10, 15, 20, 30, 50, 59, 72, 100, 150, 200, 250, 295, 300, 354, 400]

print(f"\n   N        a_N(q)           a_N/N²          გადახრა 1-დან")
print(f"   ─────    ─────────        ─────────       ─────────")
for N in N_interesting:
    try:
        a_N = mathieu_a(N, q)
        ratio = a_N / N**2
        deviation = abs(ratio - 1)
        marker = ""
        if N == 5: marker = "  ← N_e"
        elif N == 72: marker = "  ← N_μ"
        elif N == 295: marker = "  ← N_τ"
        elif N == 59: marker = "  ← ტესტ: 59?"
        print(f"   {N:4d}     {a_N:.6f}      {ratio:.8f}      {deviation:.2e}{marker}")
    except Exception as e:
        print(f"   {N:4d}     (შეცდომა: {e})")

# ===================================================================
# B. b_N კოეფიციენტები (ცენტრალური სახე — odd modes)
# ===================================================================

print("\n" + "-" * 72)
print(" B. b_N(q) ეიგენვალუები — შესადარებლად")
print("-" * 72)

print(f"\n   N        b_N(q)           b_N/N²          b_N/b_5")
print(f"   ─────    ─────────        ─────────       ─────────")
b_5 = mathieu_b(5, q)
for N in N_interesting:
    try:
        b_N = mathieu_b(N, q)
        ratio = b_N / N**2
        rel_to_5 = b_N / b_5
        marker = ""
        if N == 5: marker = "  ← N_e"
        elif N == 72: marker = "  ← N_μ (m_μ/m_e ≈ b_72/b_5)"
        elif N == 295: marker = "  ← N_τ (m_τ/m_e ≈ b_295/b_5)"
        print(f"   {N:4d}     {b_N:.4f}   {ratio:.8f}      {rel_to_5:.4f}{marker}")
    except Exception as e:
        print(f"   {N:4d}     (შეცდომა: {e})")

# ===================================================================
# C. b_N - N² გადახრა (სტრუქტურული ნიშანი?)
# ===================================================================

print("\n" + "-" * 72)
print(" C. გადახრის სიდიდე b_N - N² (სკანი ფართო)")
print("-" * 72)

N_arr = np.arange(5, 350)
b_arr = np.array([mathieu_b(int(N), q) for N in N_arr])
deviation_arr = b_arr - N_arr**2

# ვეძებთ max/min ან სპეციალურ ნიშნებს
print(f"\n   ძიება: b_N - N² ფუნქცია მონოტონურია თუ არა?")
print(f"   მინიმუმი: b_N - N² = {deviation_arr.min():.4f} at N = {N_arr[np.argmin(deviation_arr)]}")
print(f"   მაქსიმუმი: b_N - N² = {deviation_arr.max():.4f} at N = {N_arr[np.argmax(deviation_arr)]}")

# ცვლილების ნიშნი (signaling structural transitions)
sign_changes = 0
for i in range(1, len(deviation_arr)):
    if np.sign(deviation_arr[i]) != np.sign(deviation_arr[i-1]):
        sign_changes += 1
        print(f"   ნიშნის ცვლა: N = {N_arr[i]}, გადახრა {deviation_arr[i-1]:.4f} → {deviation_arr[i]:.4f}")

if sign_changes == 0:
    print(f"   ნიშნის ცვლა არაა — b_N - N² ერთი ნიშნისაა.")

# ===================================================================
# D. სპეციფიური ფარდობები: რა ხდება ზუსტად 59-ზე?
# ===================================================================

print("\n" + "-" * 72)
print(" D. 59-ის ძიება")
print("-" * 72)

# 1. თუ 59 არის რიცხვი, ის Mathieu-ში უნდა გამოიყურებოდეს როგორც
#    რაღაც სპეციფიური გადახრა a_N ან b_N-ში

a_59 = mathieu_a(59, q)
b_59 = mathieu_b(59, q)

print(f"\n   a_59(q) = {a_59:.6f}")
print(f"   b_59(q) = {b_59:.6f}")
print(f"   59² = {59**2}")
print(f"   a_59 - 59² = {a_59 - 59**2:.6f}")
print(f"   b_59 - 59² = {b_59 - 59**2:.6f}")

# ფარდობა 59-სა და 5-ს შორის
print(f"\n   ფარდობები 5-ის მიმართ:")
print(f"   a_59/a_5 = {mathieu_a(59, q)/mathieu_a(5, q):.4f}")
print(f"   b_59/b_5 = {mathieu_b(59, q)/mathieu_b(5, q):.4f}")
print(f"   (59/5)² = {(59/5)**2:.4f}")
print(f"   (m_τ/m_e დაკვირვ.) = {1776.86/0.51099895:.4f}")

# თუ 295 = 5 × 59, არის თუ არა b_295/b_5 სწორედ (59)² ?
print(f"\n   b_295/b_5 = {mathieu_b(295, q)/mathieu_b(5, q):.4f}")
print(f"   ე.ი. m_τ/m_e პროგნოზი Mathieu-ით: {mathieu_b(295, q)/mathieu_b(5, q):.1f}")
print(f"   m_τ/m_e დაკვირვ.: {1776.86/0.51099895:.1f}")

# ===================================================================
# E. ძიება: რაიმე სპეციალური N რომელზეც m_τ/m_e მიიღება?
# ===================================================================

print("\n" + "-" * 72)
print(" E. თუ m_τ/m_e = {:.2f}, რომელი N იძლევა ამას?".format(1776.86/0.51099895))
print("-" * 72)

target = 1776.86 / 0.51099895
best_N = None
best_err = float('inf')
for N in range(10, 400):
    ratio = mathieu_b(N, q) / b_5
    err = abs(ratio - target) / target
    if err < best_err:
        best_err = err
        best_N = N

print(f"\n   უახლოესი N = {best_N}")
print(f"   b_{best_N}/b_5 = {mathieu_b(best_N, q)/b_5:.4f}")
print(f"   დაკვირვ. m_τ/m_e = {target:.4f}")
print(f"   ცდომილება = {best_err*100:.3f}%")

if best_N == 295:
    print("   → Mathieu ზუსტად N=295-ს ირჩევს. ანუ 59 არ არის ცალკე რიცხვი")
    print("     — ის Mathieu-ს მასის სქემიდან გამოდის.")
else:
    print(f"   → N={best_N} (არა 295) — ე.ი. რაღაც უფრო ოპტიმალურია")

# ===================================================================
# F. დასკვნა
# ===================================================================

print("\n" + "=" * 72)
print(" F. დასკვნა")
print("=" * 72)

print("""
   რაც ვიპოვნეთ:
   ───────────────
   - Mathieu b_N(q) ∝ N² ძალიან ზუსტად უკვე N=5-ზე
   - 59 არ "გამოჩნდება" Mathieu ზოლების სტრუქტურიდან უშუალოდ
   - m_τ/m_e დაკვირვებული = 3477 → Mathieu იძლევა N=295 უახლოეს
     პასუხად (b_N/b_5 = 3477, შესაბამისად)

   რა არის 59-ის რეალური არსი:
   ─────────────────────────
   59 არ არის ცალკე სტრუქტურული რიცხვი Mathieu-ში.
   ის არის უბრალოდ ფარდობა N_τ/N_e = 295/5.

   ე.ი. ფუნდამენტური ღია კითხვა არის:
   ─────────────────────────
   რატომ N_τ = 295 (და არა რაიმე სხვა)?

   ჩვენი სურათის მიხედვით:
   - N_e = 5 (პირველი სტაბილური — დამტკიცებული)
   - N_τ = 295 (ემპირიული, პულსონის ფონიდან კონკრეტულად ვერ ამოვყავით)
   - N_μ = 72 (გამოდის Koide-დან + 295)

   სავარაუდო:
   - 295 შესაძლოა პულსონის შიდა გეომეტრიიდან გამოდის
     (რადიუსის ფარდობა, კვანძების რაოდენობა — ცალკე ტესტი საჭიროა)
   - ან 295 ფუნდამენტური ფიზიკური შესვლელია (როგორც G_F ან α)
""")

print("=" * 72)
print(" Phase 7 — დასრულდა")
print("=" * 72)
