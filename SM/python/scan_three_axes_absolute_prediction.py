"""
ISPG — Phase 3: weak-decay scaling check with no fitted coupling
================================================================

Phase 2-ში აღმოვაჩინეთ: g²(μ) ≈ g²(τ) ≈ G_F² (0.2% სიზუსტით).
ე.ი. სუსტი კუპლინგი უნივერსალურია სამივე ღერძზე.

Phase 3-ში ვცდით უფრო მძიმე ტესტს:
   გამოვთვალოთ τ_μ და τ_τ მხოლოდ G_F-ით და მასებით,
   ნულოვანი ფიტი-პარამეტრით. შევადაროთ დაკვირვებას.

სკრიპტი იყენებს იმპორტირებულ G_F-ს, გაზომილ მასებს და τ-ს
branching ratio-ს. ამიტომ sub-1% დამთხვევა ნიშნავს, რომ სურათი
ჰოსტავს standard weak-decay scaling-ს; ეს არ არის 3-ღერძიანი
გეომეტრიის დამოუკიდებელი derivation.

ასევე ვეძებთ: რას პროგნოზირებს ეს სურათი ცარიელი (e) ღერძზე —
რომელიც დაცლილია არანაირი წასასვლელი არ არის?
"""

import numpy as np

# ===================================================================
# შესვლელი — ყველაფერი ცნობილი მუდმივებია, ფიტი არაა
# ===================================================================

# PDG 2024 მასები (MeV) — არა ფიტი, გაზომული
m_e = 0.51099895
m_mu = 105.6583755
m_tau = 1776.86

# სიცოცხლეები (წმ) — გაზომული
tau_mu_obs = 2.1969811e-6
tau_tau_obs = 290.3e-15

# Fermi-ს მუდმივა — ცნობილია μ → e ν ν̄ დაშლიდან ცალკე
G_F_GeV = 1.1663787e-5             # GeV⁻²
G_F_MeV = G_F_GeV * 1e-6           # MeV⁻²

# განშტოების თანაფარდობები — PDG გაზომული
BR_tau_to_e = 0.1782

# ℏ
hbar_MeV_s = 6.582119569e-22

print("=" * 72)
print(" Phase 3 — weak-decay scaling check (0 fitted coupling)")
print("=" * 72)

print("""
შესვლელი:
  - 3 მასა (PDG)
  - G_F (β-დაშლიდან, ცალკე განსაზღვრული)
  - BR(τ→e) (PDG)
რა ვთვლით:
  - τ_μ, τ_τ
  - ახალი ფიტირებული კუპლინგი არ შეგვაქვს
""")

# ===================================================================
# Sargent-ის ფორმულა: Γ(i→eνν̄) = G_F² · m_i⁵ / (192π³)
# ერთეულებში: Γ = (G_F² m⁵ / 192π³) / ℏ
# ===================================================================

def sargent_width(m, GF2):
    """Sargent: Γ = G_F² · m⁵ / (192π³ · ℏ)"""
    return GF2 * m**5 / (192 * np.pi**3 * hbar_MeV_s)

# ===================================================================
# μ-ს სრული სიცოცხლე (მხოლოდ ერთი კანალი: μ → e ν_μ ν̄_e)
# ===================================================================

Gamma_mu_pred = sargent_width(m_mu, G_F_MeV**2)
tau_mu_pred = 1.0 / Gamma_mu_pred

print("\n" + "-" * 72)
print(" A. მიუონის სიცოცხლე")
print("-" * 72)
print(f"   Γ_μ(პროგნოზი) = G_F² · m_μ⁵ / (192π³ ℏ) = {Gamma_mu_pred:.6e} ჰც")
print(f"   τ_μ(პროგნოზი) = {tau_mu_pred:.6e} წმ")
print(f"   τ_μ(დაკვირვ.) = {tau_mu_obs:.6e} წმ")
err_mu = abs(tau_mu_pred - tau_mu_obs) / tau_mu_obs * 100
print(f"   ცდომილება:     {err_mu:.3f}%")

# ===================================================================
# τ-ის ლეპტონური სიცოცხლე (τ → e ν_τ ν̄_e) — ტოლი Sargent ფორმულა
# ===================================================================

Gamma_tau_to_e_pred = sargent_width(m_tau, G_F_MeV**2)
# სრული Γ_τ = Γ_τ(→e) / BR(τ→e)
Gamma_tau_total_pred = Gamma_tau_to_e_pred / BR_tau_to_e
tau_tau_pred = 1.0 / Gamma_tau_total_pred

print("\n" + "-" * 72)
print(" B. ტაუს სიცოცხლე")
print("-" * 72)
print(f"   Γ_τ(→e პროგნოზი)  = G_F² · m_τ⁵ / (192π³ ℏ) = {Gamma_tau_to_e_pred:.6e} ჰც")
print(f"   Γ_τ(სრ. პროგნოზი) = Γ_τ(→e) / BR(τ→e)      = {Gamma_tau_total_pred:.6e} ჰც")
print(f"   τ_τ(პროგნოზი)     = {tau_tau_pred:.6e} წმ")
print(f"   τ_τ(დაკვირვ.)     = {tau_tau_obs:.6e} წმ")
err_tau = abs(tau_tau_pred - tau_tau_obs) / tau_tau_obs * 100
print(f"   ცდომილება:        {err_tau:.3f}%")

# ===================================================================
# C. ელექტრონის "პროგნოზი" — რა იქნებოდა, თუ კანალი არსებობდეს?
# ===================================================================

print("\n" + "-" * 72)
print(" C. ელექტრონი — ვირტუალური Sargent-წესი (მხოლოდ კინემატიკის გასააზრებლად)")
print("-" * 72)
Gamma_e_virtual = sargent_width(m_e, G_F_MeV**2)
tau_e_virtual = 1.0 / Gamma_e_virtual
print(f"   თუ ელექტრონს ქონდა დაშლის კანალი:")
print(f"     Γ_e(ვირტ.) = {Gamma_e_virtual:.4e} ჰც")
print(f"     τ_e(ვირტ.) = {tau_e_virtual:.4e} წმ  ≈  {tau_e_virtual/(3.15e16):.2e} გიგაწელი")
print(f"   სამყაროს ასაკი:         4.35e+17 წმ  (≈ 13.8 მილიარდი წელი)")
print(f"\n   ე.ი. თუნდაც კანალი არსებობდეს, ელექტრონი მაინც სამყაროზე მეტ-ხანს")
print(f"   ვერ ცოცხლობდა — მაგრამ ფიზიკურად კანალი არ არის (m < m_e ლეპტონი არ არსებობს).")

# ===================================================================
# D. ცარიელი ღერძის დამპფირება
# ===================================================================

print("\n" + "-" * 72)
print(" D. რატომ e-ს არა, μ-ს კი?")
print("-" * 72)
print("""
   Sargent-ის წესი მოითხოვს:
     ↓
     m_საწყ > m_ბოლო + 2·m_ν
     ↓
     ე.ი. ღერძს "გადასასვლელი" უნდა ქონდეს უფრო დაბალ ღერძზე.

   x-ღერძი (e):   არ არის დაბალი ღერძი  →  γ = 0
   y-ღერძი (μ):   x არის ქვემოთ          →  γ = G_F² m_μ⁵ / (192π³ ℏ)
   z-ღერძი (τ):   x, y არიან ქვემოთ     →  γ = G_F² m_τ⁵ / (192π³ ℏ) · N_კანალი

   ⇒ დამპფირების იერარქია კინემატიკიდანაა, არა ცალკე პარამეტრებიდან.
""")

# ===================================================================
# E. შეჯამება
# ===================================================================

print("=" * 72)
print(" E. შეჯამება")
print("=" * 72)

print(f"""
   weak-decay scaling check:
   ────────────────────────────────
   τ_μ(პროგ.) = {tau_mu_pred:.4e} წმ
   τ_μ(გაზ.)  = {tau_mu_obs:.4e} წმ
   ცდომილება: {err_mu:.3f}% ← ტრივიალურად მცირე

   τ_τ(პროგ.) = {tau_tau_pred:.4e} წმ
   τ_τ(გაზ.)  = {tau_tau_obs:.4e} წმ
   ცდომილება: {err_tau:.3f}% ← ტრივიალურად მცირე

   ძირითადი დასკვნა:
   ────────────────────────────────
   3-ღერძიანი სურათი არ მოითხოვს თავის კუპლინგს ან დამპფირებას —
   ყველაფერი გამოდის ცნობილი G_F-ისგან და მასებისგან.

   ეს ნიშნავს, რომ სურათი თავსებადია known weak-decay scaling-თან:
   ერთი და იგივე G_F მუშაობს μ და τ ღერძებზე. ეს არის hosting/
   compatibility check და არა 3-ღერძიანი გეომეტრიის დამოუკიდებელი
   derivation.

   რაც კვლავ ახსნა უნდა:
   ────────────────────────────────
   1. რატომ m_μ/m_e = 207 და m_τ/m_e = 3477?
      (ანიზოტროპიის წარმოშობა — Phase 4-ისთვის)
   2. რატომ ω_τ/ω_e = 59 ზუსტად მთელი, ხოლო ω_μ/ω_e = 14.4 — არა?
      (შესაძლოა "59" სიმეტრიული ფაქტია)
""")

print("=" * 72)
print(" Phase 3 — დასრულდა")
print("=" * 72)
