"""
ISPG — არიან თუ არა 5, 72, 295 ჰარმონიკები?
==============================================
სამი განსხვავებული „ჰარმონიკის" გაგება:

(I)  უბრალო ჯერადი:   N_j / N_i = მთელი?
(II) ორი ფუძის ჯამი:   N = n·f₁ + m·f₂?
(III) Mathieu-ს N-ე რეზონანსი: ყოველი N თვითონ ჰარმონიკაა პულსონის.
"""
import numpy as np
from itertools import product

N = [5, 72, 295]
labels = ["e", "μ", "τ"]

print("=" * 70)
print("  (I)  წრფივი ჰარმონიკული კავშირი — ერთი ფუძე")
print("=" * 70)
for i in range(3):
    for j in range(3):
        if i < j:
            ratio = N[j] / N[i]
            is_int = abs(ratio - round(ratio)) < 0.01
            mark = "✓ მთელი!" if is_int else ""
            print(f"   N_{labels[j]}/N_{labels[i]} = {N[j]}/{N[i]} = {ratio:.4f}  {mark}")

print("\n  დასკვნა:")
print("     • 295/5 = 59 ზუსტად — ტაუ არის ელექტრონის **59-ე ჰარმონიკა**")
print("     • 72/5 = 14.4 — მიუონი **არ არის** ელექტრონის ჰარმონიკა")
print("     • 295/72 = 4.097 — ტაუ **არ არის** მიუონის ჰარმონიკა")

print("\n" + "=" * 70)
print("  (II)  ორი ფუძის კომბინაცია: N = n·f₁ + m·f₂")
print("=" * 70)
# თუ f₁=5 (ელექტრონის ფუძე), მაშინ f₂=?
# 72 = n·5 + m·f₂  →  f₂ = (72-5n)/m
# 295 = n'·5 + m'·f₂
# ერთი საერთო f₂ უნდა იყოს ორივე განტოლებისთვის

best = None
best_err = 1e9
for f2 in range(2, 50):
    for n in range(0, 20):
        for m in range(1, 20):
            pred_mu = n*5 + m*f2
            if pred_mu != 72:
                continue
            for n2 in range(0, 70):
                for m2 in range(0, 50):
                    pred_tau = n2*5 + m2*f2
                    if pred_tau == 295:
                        print(f"   ✓  f₁=5, f₂={f2}:")
                        print(f"        μ = {n}·5 + {m}·{f2} = 72")
                        print(f"        τ = {n2}·5 + {m2}·{f2} = 295")
                        if best is None or (n+m+n2+m2) < best[0]:
                            best = (n+m+n2+m2, f2, n, m, n2, m2)
                        break
                else:
                    continue
                break

if best is None:
    print("     მარტივი (f₁=5, f₂≤50) გადაწყვეტა არ აღმოჩნდა.")
else:
    _, f2, n, m, n2, m2 = best
    print(f"\n   ყველაზე მარტივი: f₂={f2},  μ = {n}·5 + {m}·{f2},  τ = {n2}·5 + {m2}·{f2}")

print("\n" + "=" * 70)
print("  (III)  Mathieu-ს რეზონანსი: ყველა N თვითონ პულსონის ჰარმონიკაა")
print("=" * 70)
print("""
   Mathieu-ს ფუძე-განტოლება:
       ψ'' + [a_N − 2q cos(2τ)] ψ = 0
   ყოველი N ∈ ℕ არის **პარამეტრული რეზონანსის N-ე ოვერტონი**.
   ე.ი. 5, 72, 295 — სამივე ჰარმონიკაა პულსონის ფონური სიხშირისა.

   **მაგრამ არიან უცვლელი ჰარმონიკები ≠ სტაბილური**:
     N=1,2,3  →  რეზონანსი ძალიან ძლიერი, სწრაფად იშლება
     N=4      →  ზღვრული სტაბილურობა
     N=5,6,…  →  სტაბილური (მაგრამ gap ≠ 0)

   ფიზიკური მინიშნება: **ამორჩევითი წესი** ხდის 5, 72, 295-ს
   განსაკუთრებულად. უბრალო „ყოველი N" — **არ ხდება** ლეპტონი.
""")

print("=" * 70)
print("  ჰიპოთეზა: რეზონანსული ოჯახების სტრუქტურა")
print("=" * 70)
print(f"""
   შემჩნეული ფაქტი:
      295 = 59 × 5  (ტაუ = ელექტრონის ზუსტი ჰარმონიკა)
      72  ≠ 5 × მთელი (მიუონი სხვა ოჯახშია)

   შესაძლო ინტერპრეტაცია:
     • ელექტრონი და ტაუ — ერთი რეზონანსული ოჯახი (ფუძე + ოვერტონი)
     • მიუონი — მეორე ოჯახის ფუძე (სხვა სიმეტრიული მოდი)

   პროგნოზი: თუ ოჯახური სტრუქტურა სწორია, უნდა არსებობდეს
   მიუონის ჰარმონიკაც 72 × k რომელიმე k ∈ ℕ-სთვის:
      72 × 2 = 144,   72 × 3 = 216,   72 × 4 = 288,   72 × 5 = 360
   წმინდა ლეპტონებში ასეთი არ გვაქვს — მხოლოდ τ=295.
   მაგრამ MASS paper-ში კვარკებზე ვნახოთ: c=250, b=453, t=2910.
""")

# შევამოწმოთ კვარკებისთვის
quarks_N = {"c": 250, "b": 453, "t": 2910, "s": 68, "u": 10, "d": 15}
print("   კვარკების N-ების დამოკიდებულება 5-ზე და 72-ზე:")
for name, n in quarks_N.items():
    r5 = n / 5
    r72 = n / 72
    print(f"     {name} (N={n:4d}):  N/5 = {r5:7.3f}   N/72 = {r72:7.3f}")
